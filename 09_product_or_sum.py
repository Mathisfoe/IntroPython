nombre1 = int(input("Insère un premier nombre entier : "))
nombre2 = int(input("Insère un deuxième nombre entier : "))
if nombre1 * nombre2 <= 1000 :
    print(f"Le résultat de {nombre1} * {nombre2} est {nombre1 * nombre2}")
else :
    print (f"Le résultat de {nombre1} + {nombre2} est {nombre1 + nombre2}")